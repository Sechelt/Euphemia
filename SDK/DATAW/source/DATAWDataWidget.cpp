DATAWDataWidget::DATAWDataWidget( AWObject *pObject, QWidget *pParent, DATAConnection *p, const QString &stringCatalog, const QString &stringSchema, const QString &stringTable  )
: AWEditorWidget( pObject, pParent )
{
// printf( "[%s][%s][%d] [%s][%s][%s]\n", __FILE__, __FUNCTION__, __LINE__, stringCatalog.toUtf8().constData(), stringSchema.toUtf8().constData(), stringTable.toUtf8().constData() );
    setObjectName( metaObject()->className() );
    pConnection         = p;
    this->stringCatalog = stringCatalog;
    this->stringSchema  = stringSchema;
    this->stringTable   = stringTable;
    nRows                   = 0;
    nMaxRows                = 5000;
            
    QToolBar *pToolBar = addToolBar( "Navigation" );
    WDataNavWidget *pNavigation = new WDataNavWidget( pToolBar );
    pToolBar->addWidget( pNavigation );

    ptableResults = new QTableWidget();
    ptableResults->setRowCount( 1 );
    setCentralWidget( ptableResults );

    doLoadState();

    // no connection no joy
    if ( !pConnection ) return;
    if ( !pConnection->isConnected() ) return;

    // no rowid no edit
    listRowID   = getRowID();
    listColumns = getColumns();

    // build complete column list including any 'hidden' RowID
    listColumnsQuery = listColumns;
    foreach ( const QString &s, listRowID )
    {
        if ( !listColumnsQuery.contains( s ) ) listRowID.insert( 0, s );
    }

    // build query string specifiying columns ex0plicitly
    stringQuery = "SELECT ";
    bool bFirst = true;
    foreach ( const QString &s, listColumnsQuery )
    {
        if ( !bFirst ) stringQuery += ", "; else bFirst = false;
        stringQuery += s;
    }
    stringQuery += " FROM " + stringTable;

// printf( "[%s][%s][%d] %s\n", __FILE__, __FUNCTION__, __LINE__, stringQuery.toUtf8().constData() );
    //
    pStatement = pConnection->getExecute( stringQuery );
    if ( !pStatement ) return;                                                      
    doResultGUIGrid();
}


